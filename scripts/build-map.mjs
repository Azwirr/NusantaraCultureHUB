// Builds src/lib/map/indonesia-provinces.ts from Natural Earth's admin-1
// layer (public domain, https://www.naturalearthdata.com).
//
//   1. Download ne_10m_admin_1_states_provinces.geojson (Natural Earth 5.1.2)
//      from github.com/nvkelso/natural-earth-vector into a folder of its own.
//   2. node scripts/build-map.mjs <path to that file>
//
// The 40 MB source stays out of the repository. mapshaper keeps Indonesia,
// simplifies the outlines, and this script projects them (equirectangular,
// fine this close to the equator) into SVG path data.
//
// Known gap: Natural Earth 5.1.2 predates the 2022 Papua split and still has
// North Kalimantan inside East Kalimantan, so it has 33 of the 38 provinces.
// The map says so. Our regions use provinces it has exactly.

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import mapshaper from "mapshaper";

const input = process.argv[2];
if (!input) {
  console.error("usage: node scripts/build-map.mjs <ne_10m_admin_1_states_provinces.geojson>");
  process.exit(1);
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "src", "lib", "map", "indonesia-provinces.ts");

const result = await mapshaper.applyCommands(
  [
    `-i "${input}"`,
    `-filter 'adm0_a3 == "IDN"'`,
    "-filter-fields iso_3166_2,name",
    "-simplify 4% keep-shapes",
    "-filter-slivers min-area=20km2",
    "-o out.json format=geojson precision=0.001",
  ].join(" "),
);
const geojson = JSON.parse(result["out.json"].toString());

// Equirectangular projection into a 1000-unit-wide viewBox.
const WEST = 94.8;
const EAST = 141.2;
const NORTH = 6.2;
const SOUTH = -11.2;
const SCALE = 1000 / (EAST - WEST);
const project = ([lon, lat]) => [(lon - WEST) * SCALE, (NORTH - lat) * SCALE];
const round = (value) => Math.round(value * 10) / 10;

function ringToPath(ring) {
  const points = ring.map(project).map(([x, y]) => `${round(x)} ${round(y)}`);
  return `M${points.join("L")}Z`;
}

function geometryToPath(geometry) {
  const polygons = geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  return polygons.flatMap((polygon) => polygon.map(ringToPath)).join("");
}

const provinces = geojson.features
  .map((feature) => ({
    code: feature.properties.iso_3166_2,
    name: feature.properties.name,
    d: geometryToPath(feature.geometry),
  }))
  .sort((a, b) => a.code.localeCompare(b.code));

const width = Math.round((EAST - WEST) * SCALE);
const height = Math.round((NORTH - SOUTH) * SCALE);

const source = `// Generated by scripts/build-map.mjs from Natural Earth 5.1.2 admin-1
// (public domain). Do not edit by hand. ${provinces.length} provinces: the 2022
// Papua provinces and North Kalimantan are not separate in this release.

export const MAP_VIEWBOX = "0 0 ${width} ${height}";

export const PROVINCE_SHAPES: ReadonlyArray<{ code: string; name: string; d: string }> = ${JSON.stringify(provinces, null, 2)};
`;

await writeFile(output, source);
console.log(`wrote ${path.relative(root, output)}: ${provinces.length} provinces, ${(source.length / 1024).toFixed(0)} KB`);
